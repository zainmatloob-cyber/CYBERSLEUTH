"""Choose the cut-off for model-only technique suggestions on real advisories (dev split only).

Usage:
    python scripts/choose_real_world_threshold.py \
        --manifest data/real_world/batch2/manifest.json

The rule was fixed before this script was first run:

* candidates: decision scores 0.25, 0.5 and 0.75 (the current training threshold is shown
  for comparison only);
* choose the **lowest** candidate at which at least half of the model-only suggestions
  (score >= candidate) match a technique CISA cites, at parent level;
* if no candidate reaches that, choose none: model suggestions stay hidden by default.

A model-only suggestion is a document-level mapping with no explicit evidence. Its score is
its best sentence score (``max_score``), which is exactly what the mapper's cut-off compares.
Negated mappings are excluded, as in the evaluation. The mapper runs with the document-level
cut-off turned off, so the result doesn't depend on a previously chosen value.

Writes ``docs/evaluation/real_world_threshold.md`` and ``.json``. It never reads the test
split.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.evaluation import manifest as rm  # noqa: E402
from src.evaluation import real_world as rw  # noqa: E402
from src.evaluation.real_world import wilson  # noqa: E402

CANDIDATES = (0.25, 0.5, 0.75)
TARGET_AGREEMENT = 0.5
OUT_JSON = ROOT / "docs" / "evaluation" / "real_world_threshold.json"
OUT_MD = ROOT / "docs" / "evaluation" / "real_world_threshold.md"


def at_threshold(suggestions: list[dict], threshold: float) -> dict:
    kept = [s for s in suggestions if s["score"] >= threshold]
    agree = sum(s["cited_parent"] for s in kept)
    interval = wilson(agree, len(kept))
    return {"threshold": threshold, "kept": len(kept), "agree": agree,
            "agreement": agree / len(kept) if kept else None,
            "interval": [round(v, 3) for v in interval] if interval else None,
            "documents_with_suggestions": len({s["document"] for s in kept})}


def choose(rows: list[dict], target: float = TARGET_AGREEMENT) -> float | None:
    """The lowest candidate whose agreement reaches ``target`` (rows sorted by threshold)."""
    for row in sorted(rows, key=lambda r: r["threshold"]):
        if row["agreement"] is not None and row["agreement"] >= target:
            return row["threshold"]
    return None


def collect(documents: list[dict], gold: dict) -> list[dict]:
    from src.intelligence.analyzer import Analyzer
    from src.intelligence.attack_kb import default_technique_kb
    from src.intelligence.mitre_mapper import TechniqueMapper

    kb = default_technique_kb()
    mapper = TechniqueMapper(kb, model_only_min_score=None)
    if mapper.model is None:
        raise SystemExit("The technique model is not loaded; train it first.")
    analyzer = Analyzer(technique_mapper=mapper)
    suggestions = []
    for doc in documents:
        truth = rw.parents(gold["documents"][doc["id"]]["techniques"], kb)
        result = analyzer.analyze(doc["pdf_path"].read_bytes(), doc["pdf_path"].name)
        for m in rw.asserted(result.mappings):
            if rw.prediction_group(m) != "model_only":
                continue
            suggestions.append({
                "document": doc["id"], "technique": m.technique_id, "name": m.name,
                "score": round(m.max_score, 4), "sentences": len(m.evidence),
                "cited_parent": (kb.parent(m.technique_id) or m.technique_id) in truth})
        print(f"{doc['id']}: {len(truth)} cited parents, "
              f"{sum(s['document'] == doc['id'] for s in suggestions)} model-only suggestions")
    return suggestions


def render(result: dict) -> str:
    def pct(v):
        return "n/a" if v is None else f"{v:.2f}"

    chosen = result["chosen"]
    lines = [
        "# Real-world cut-off for model-only technique suggestions",
        "",
        "Generated by `scripts/choose_real_world_threshold.py` on the **development split** "
        f"of the second CISA set ({len(result['documents'])} advisories). The test split was "
        "not read.",
        "",
        "**Rule (fixed before the first run):** among the candidates "
        f"{', '.join(str(c) for c in CANDIDATES)}, choose the lowest decision score at "
        f"which at least {TARGET_AGREEMENT:.0%} of model-only suggestions match a technique "
        "CISA cites (parent level). If none does, choose none.",
        "",
        "| Cut-off | Suggestions kept | Agree with CISA | Agreement | 95% interval* | "
        "Advisories with a suggestion |",
        "|---|---|---|---|---|---|",
    ]
    for row in [result["baseline"], *result["candidates"]]:
        label = (f"{row['threshold']:.3f} (current training threshold)"
                 if row is result["baseline"] else f"{row['threshold']:.2f}")
        interval = ("n/a" if row["interval"] is None
                    else f"{row['interval'][0]:.2f}–{row['interval'][1]:.2f}")
        lines.append(f"| {label} | {row['kept']} | {row['agree']} | {pct(row['agreement'])} "
                     f"| {interval} | {row['documents_with_suggestions']} |")
    lines += [
        "",
        "\\* Wilson interval treating suggestions as independent. They are not (suggestions "
        "from one advisory are correlated), so the true uncertainty is wider.",
        "",
        "## Decision",
        "",
    ]
    if chosen is None:
        lines.append(f"No candidate reaches {TARGET_AGREEMENT:.0%}. No cut-off is set; model "
                     "suggestions stay hidden by default.")
    else:
        lines.append(f"**Chosen cut-off: {chosen}.** It is the lowest candidate that reaches "
                     f"{TARGET_AGREEMENT:.0%} agreement on the development split. It is set "
                     "as `model_only_min_score` in `config/technique_mapping.json` and is "
                     "tested once on the test split.")
    lines += [
        "",
        "## Per advisory (development split)",
        "",
        "| Advisory | Model-only suggestions (no cut-off) | Kept at the chosen cut-off | "
        "Kept and agree |",
        "|---|---|---|---|",
    ]
    for doc_id, d in result["per_document"].items():
        lines.append(f"| {doc_id} | {d['all']} | {d['kept']} | {d['kept_agree']} |")
    lines += [
        "",
        "## Caveats",
        "",
        "* Agreement is a lower bound on precision: CISA's technique lists are incomplete.",
        "* The candidate values came from the first set's error analysis, which is why the "
        "first set can't be used to test them.",
        "* Nine advisories is a small development set; the test split gives the number to "
        "report.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    if "split" not in manifest:
        raise SystemExit("The manifest has no development split.")
    dev = [d for d in manifest["documents"] if d.get("split") == "dev"]
    manifest = {**manifest, "documents": dev}  # the test split is never loaded
    documents = rm.verified_documents(manifest, rm.raw_dir(manifest, ROOT))
    gold = json.loads((args.manifest.parent / "gold.json").read_text(encoding="utf-8"))

    from src.intelligence.mitre_mapper import TechniqueModel

    baseline_threshold = TechniqueModel.load().threshold
    suggestions = collect(documents, gold)
    candidates = [at_threshold(suggestions, t) for t in CANDIDATES]
    chosen = choose(candidates)
    per_document = {}
    for doc in documents:
        mine = [s for s in suggestions if s["document"] == doc["id"]]
        kept = [s for s in mine if chosen is not None and s["score"] >= chosen]
        per_document[doc["id"]] = {"all": len(mine), "kept": len(kept),
                                   "kept_agree": sum(s["cited_parent"] for s in kept)}
    result = {
        "documents": [d["id"] for d in documents],
        "rule": {"candidates": list(CANDIDATES), "target_agreement": TARGET_AGREEMENT,
                 "choose": "lowest candidate reaching the target"},
        "baseline": at_threshold(suggestions, baseline_threshold),
        "candidates": candidates, "chosen": chosen, "per_document": per_document,
        "suggestions": suggestions,
    }
    OUT_JSON.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    OUT_MD.write_text(render(result), encoding="utf-8")
    for row in [result["baseline"], *candidates]:
        print(f"cut-off {row['threshold']:.3f}: kept {row['kept']}, agreement "
              f"{row['agreement']}")
    print(f"Chosen: {chosen}. Wrote {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
